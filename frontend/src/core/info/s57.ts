/** Title for one tile feature's class. ATON has to be un-merged: the tiler
 * routes every buoy/beacon class into it, dropping the acronym. BOYSHP/BCNSHP
 * are the surviving discriminator; neither mandatory, so generic name falls back. */
export function classTitle(sourceLayer: string, props: Readonly<Record<string, unknown>>): string {
  if (sourceLayer === "ATON") {
    if (props.BOYSHP !== undefined) return "Buoy";
    if (props.BCNSHP !== undefined) return "Beacon";
  }
  return CLASS_TITLE[sourceLayer] ?? sourceLayer;
}

