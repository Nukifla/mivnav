/** Codes S-57 reserves across every enumerated attribute. */
const UNIVERSAL_CODES: Record<number, string> = { 0: "unknown" };

/** Attributes we have a label for, in display order. */
const ORDERED_ATTRS = [
  ...LEAD_ATTRS,
  ...Object.keys(ATTR_LABELS).filter((a) => !LEAD_ATTRS.includes(a)),
];

/** Sort key for an attribute acronym: known ones in `ORDERED_ATTRS` order,
 * unknown ones after them, alphabetically. */
export function attrOrder(acronym: string): number {
  const i = ORDERED_ATTRS.indexOf(acronym);
  return i < 0 ? ORDERED_ATTRS.length : i;
}

export function attrLabel(acronym: string): string {
  return ATTR_LABELS[acronym] ?? acronym;
}

/** Is this key raw chart truth rather than one of chartcore's derived facts?
 * Case is the whole rule: S-57 acronyms are uppercase, chartcore's synthetic
 * `DEPTH` aside every derived fact it emits is lower_snake_case. */
export function isS57Attr(key: string): boolean {
  return /^[A-Z][A-Z0-9]*$/.test(key);
}

/**
 * Trim chartcore's baked `litdsn` (`derive/lights.rs::litdsn`, OpenCPN's
 * LITDSN01) down to characteristic + period for a composite subtitle
 * ("No 3 · Fl(2)WR 5s"): keep up to the period token (`\d+s`), else strip
 * trailing height/range by shape (`m`/`ft`/`fm`/`Nm`/`NM`/`M`).
 */
export function trimLitdsn(litdsn: unknown): string | undefined {
  if (typeof litdsn !== "string") return undefined;
  const tokens = litdsn.trim().split(/\s+/).filter(Boolean);
  const period = tokens.findIndex((t) => /^\d[\d.]*s$/.test(t));
  if (period >= 0) return tokens.slice(0, period + 1).join(" ") || undefined;
  // No standalone period token (a fixed light, or a two-digit period fused to
  // the characteristic as "Fl(2)10s"): strip trailing height/range by shape.
  while (tokens.length && /^\d[\d.]*(m|ft|fm|Nm|NM|M)$/.test(tokens[tokens.length - 1])) tokens.pop();
  return tokens.join(" ") || undefined;
}

/**
 * Attribute value as a mariner reads it. Enumerated attributes decode code
 * → meaning; list-valued ones arrive comma-joined and decode element-wise.
 * An unknown code keeps its number rather than vanishing.
 */
export function decodeAttr(acronym: string, value: unknown): string {
  if (value === null || value === undefined) return "";
  const table = ENUMS[acronym];
  if (!table) return String(value);
  const decode = (raw: string): string => {
    const code = Number(raw.trim());
    if (!Number.isFinite(code)) return raw.trim();
    return table[code] ?? UNIVERSAL_CODES[code] ?? `${code}`;
  };
  const text = String(value);
  return text.includes(",")
    ? text.split(",").map(decode).filter(Boolean).join(", ")
    : decode(text);
}
