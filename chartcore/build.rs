//! Embeds `assets/s52-icons/*.svg` into the binary as a sorted
//! `&[(name, contents)]` table — the pyo3 wheel the backend imports has no
//! chartcore source tree on the Pi, so reading assets from
//! `CARGO_MANIFEST_DIR` at runtime (the old approach) doesn't work there.

use std::path::Path;

fn main() {
    let assets = Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/s52-icons");
    println!("cargo:rerun-if-changed=assets/s52-icons");

    // Sorted: read_dir has no defined order, and catalog::build_table's
    // ambiguous-id tie-break depends on alphabetical file order.
    let svg_stems = |dir: &Path| -> Vec<String> {
        let mut v: Vec<String> = std::fs::read_dir(dir)
            .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|ext| ext == "svg"))
            .filter_map(|p| p.file_stem().map(|s| s.to_string_lossy().into_owned()))
            .collect();
        v.sort();
        v
    };

    let mut names = svg_stems(&assets);
    assert!(!names.is_empty(), "{}: no *.svg", assets.display());

    // TEMPORARY stand-ins for symbols with no vendored artwork yet; usually
    // absent (empty list). See docs/architecture/aton-icon-loading.md.
    let placeholders = assets.join("placeholder");
    let placeholder_names = if placeholders.is_dir() {
        svg_stems(&placeholders)
    } else {
        Vec::new()
    };
    for name in &placeholder_names {
        assert!(
            !names.contains(name),
            "placeholder/{name}.svg shadows a real vendored icon of the same \
             name — delete the placeholder, it is no longer a gap"
        );
    }
    names.extend(placeholder_names.iter().cloned());
    names.sort();

    let mut out = String::from(
        "/// Every vendored base icon, `(file stem, file contents)`, sorted by \
         stem. Generated by `build.rs`.\n\
         pub static EMBEDDED_ICONS: &[(&str, &str)] = &[\n",
    );
    for name in &names {
        let path = if placeholder_names.contains(name) {
            placeholders.join(format!("{name}.svg"))
        } else {
            assets.join(format!("{name}.svg"))
        };
        out.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            name,
            path.to_str().expect("asset path is not UTF-8")
        ));
    }
    out.push_str("];\n\n");

    out.push_str(
        "/// The subset of [`EMBEDDED_ICONS`] that are TEMPORARY placeholders \
         (`assets/s52-icons/placeholder/`), sorted. Generated by `build.rs`; \
         see `assets/s52-icons/placeholders.json` for what each one stands in \
         for and why.\n\
         pub static PLACEHOLDER_ICONS: &[&str] = &[\n",
    );
    for name in &placeholder_names {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n");

    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("s52_icons.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}
