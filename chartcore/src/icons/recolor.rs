mod tests {
    use super::*;
    use crate::icons::catalog;

    /// Every `COLORING{}` base icon in `chartcore/assets/s52-icons/`, as of
    /// `skrqzlsx` — checked against the live directory below so this list
    /// can't silently drift from the vendored assets.
    const PARAMETRIC_ICONS: &[&str] = &[
        "2_cones_base_together",
        "2_cones_down",
        "2_cones_point_together",
        "2_cones_up",
        "2_spheres",
        "barrel",
        "cairn",
        "can",
        "circle",
        "cone_point_down",
        "cone_point_up",
        "conical",
        "cross",
        "cylinder",
        "flag",
        "floodlight",
        "lattice",
        "light",
        "light_float",
        "perch",
        "pile",
        "pillar",
        "pole",
        "post",
        "rhombus",
        "spar",
        "sphere",
        "sphere_over_rhombus",
        "spherical",
        "square",
        "stake",
        "super-buoy",
        "tower",
        "triangle_point_down",
        "triangle_point_up",
        "x-shape",
    ];

    #[test]
    fn parametric_icon_list_matches_the_vendored_assets() {
        let mut on_disk: Vec<String> = catalog::icon_names()
            .filter(|n| catalog::load_icon(n).is_ok_and(|s| catalog::is_parametric(&s)))
            .map(str::to_string)
            .collect();
        on_disk.sort();
        let mut expected: Vec<String> = PARAMETRIC_ICONS.iter().map(|s| s.to_string()).collect();
        expected.sort();
        assert_eq!(on_disk, expected);
    }

    /// The task's own verify criterion: generate every legal shape x
    /// colour x pattern combination and confirm the output is well-formed
    /// SVG. `recolor_variant` already runs every result through `usvg`
    /// (see `normalize`), so a well-formed failure surfaces as `Err`
    /// here — this test is exhaustive, not a sample, across all 36
    /// parametric base icons.
    #[test]
    fn every_legal_combination_of_every_parametric_icon_renders_well_formed_svg() {
        let mut total = 0usize;
        for icon in PARAMETRIC_ICONS {
            let base = catalog::load_icon(icon).unwrap();
            let combos = legal_combinations(icon, &base).unwrap();
            assert!(
                !combos.is_empty(),
                "{icon} has no legal combinations at all"
            );
            for (pattern, colours) in &combos {
                let svg = recolor_variant(&base, *pattern, colours)
                    .unwrap_or_else(|e| panic!("{icon} {pattern:?} {colours:?}: {e}"));
                assert!(
                    svg.starts_with("<svg"),
                    "{icon} {pattern:?} {colours:?}: not a bare <svg>: {svg}"
                );
                total += 1;
            }
        }
        // Sanity floor, not an exact count (this crate's `resolve` never
        // enumerates for real; only `legal_combinations`/this test do).
        // Currently 4742 — close to genicons.py's own reference run
        // (`icons/` at the vendored commit, `PYTHONPATH=scripts python3
        // scripts/genicons.py`), which produced 4878 real files across all
        // 172 base icons (parametric and pass-through); the 36 parametric
        // icons alone account for the bulk of that.
        assert!(
            total > 2000,
            "only generated {total} combinations, expected several thousand"
        );
    }

    #[test]
    fn pillar_horizontal_red_white_matches_genicons_reference_colours() {
        // Cross-checked by hand against a real run of genicons.py at the
        // vendored commit: `gen/pillar/horizontal/red_white.svg` paints
        // the first horizontal segment class (`horizontal02`) `#ed1c24`
        // and the second (`horizontal12`/`horizontal24`) `#ffffff`.
        let base = catalog::load_icon("pillar").unwrap();
        let svg =
            recolor_variant(&base, Some("horizontal"), &[Some("red"), Some("white")]).unwrap();
        assert!(svg.contains("#ed1c24"));
        assert!(svg.contains("#ffffff"));
    }

    /// Further hand-checked spot checks against real `genicons.py` output
    /// (`icons/gen/<icon>/<pattern>/<colours>.svg` from a clone at the
    /// vendored commit), across icons/patterns/section-counts the first
    /// one doesn't exercise: a 2-colour `squared` split, a 2-colour
    /// `border` split, a 2-colour `cross` split, and a 3-segment (2-colour,
    /// alternating) `vertical` split.
    #[test]
    fn further_combinations_match_genicons_reference_colours() {
        let cases: &[(&str, &str, &[Option<&str>], &[&str])] = &[
            (
                "tower",
                "squared",
                &[Some("black"), Some("white")],
                &["#000000", "#ffffff"],
            ),
            (
                "flag",
                "border",
                &[Some("red"), Some("green")],
                &["#ed1c24", "#00a650"],
            ),
            (
                "triangle_point_up",
                "cross",
                &[Some("yellow"), Some("black")],
                &["#fab20b", "#000000"],
            ),
            (
                "cairn",
                "vertical",
                &[Some("black"), Some("red"), Some("black")],
                &["#000000", "#ed1c24"],
            ),
        ];
        for (icon, pattern, colours, expect_hexes) in cases {
            let base = catalog::load_icon(icon).unwrap();
            let svg = recolor_variant(&base, Some(pattern), colours).unwrap();
            for hex in *expect_hexes {
                assert!(
                    svg.to_lowercase().contains(&hex.to_lowercase()),
                    "{icon}/{pattern}: missing {hex} in {svg}"
                );
            }
        }
    }

    #[test]
    fn light_float_generic_is_genicons_blank_filename_not_a_real_colour() {
        // `gen/light_float/generic.svg` in the upstream reference output
        // is genicons.py's *filename* substitute for a blank colour
        // (`"_".join(c or "generic" for c in cs)`) — light_float is
        // bucketed under the ordinary object-colour palette (see
        // `resolve_word`'s comment), not `light_colors`, so it never has a
        // real "generic" colour choice; only `light`/`floodlight` do.
        let base = catalog::load_icon("light_float").unwrap();
        let svg = recolor_variant(&base, None, &[None]).unwrap();
        assert!(
            svg.contains(r#"id="path1" fill="none" stroke="none""#),
            "expected the body path unpainted: {svg}"
        );
    }

    #[test]
    fn x_shape_uniform_yellow_overrides_the_files_own_debug_style() {
        // x-shape.svg's native <style> paints .outline red / .fill grey
        // (an Inkscape editing aid) — our injected base defaults must win
        // regardless, exactly as genicons.py's hardcoded inline `style=`
        // does.
        let base = catalog::load_icon("x-shape").unwrap();
        let svg = recolor_variant(&base, None, &[Some("yellow")]).unwrap();
        assert!(
            !svg.contains("grey"),
            "native debug fill leaked through: {svg}"
        );
        assert!(
            !svg.to_lowercase().contains("red"),
            "native debug outline leaked through: {svg}"
        );
        assert!(svg.contains("#fab20b"), "expected yellow: {svg}");
    }

    #[test]
    fn blank_colour_leaves_the_segment_invisible() {
        let base = catalog::load_icon("sphere").unwrap();
        let svg = recolor_variant(&base, None, &[None]).unwrap();
        // No fill colour requested: the "fill" role stays at its base
        // default (invisible), only the outline/baseline/basepoint show.
        assert!(!svg.contains("fill=\"#"));
    }

    #[test]
    fn unavailable_section_count_is_reported_not_silently_wrong() {
        let base = catalog::load_icon("pillar").unwrap();
        // pillar has no 5-section horizontal split.
        let err = recolor_variant(&base, Some("horizontal"), &[Some("red"); 5]).unwrap_err();
        assert!(matches!(err, RecolorError::UnknownVariant { .. }));
    }
}
