//! The recolor pass itself: a Rust port of quantenschaum/mapping's
//! `scripts/genicons.py`, which paints the `fill`/`outline`/`inline`/
//! `baseline`/`basepoint` CSS-classed regions of a base icon SVG (vendored
//! to `chartcore/assets/s52-icons/`) with a chosen colour per pattern
//! segment. Unlike genicons.py's text-substitution, this builds a real CSS
//! stylesheet and hands the whole SVG to `usvg` to resolve and bake down.
//! Cascade-ordering rationale, base-role defaults, and the
//! `structural_patterns` vs. `legal_combinations` split: see
//! docs/architecture/s52-icon-recolor.md.

use std::collections::BTreeSet;
use std::fmt;

use super::{palette, roles, ColourMode};

#[derive(Debug)]
pub enum RecolorError {
    /// The base SVG has no `COLORING{}` placeholder — it isn't a
    /// parametric icon (see [`super::catalog::is_parametric`]).
    NotParametric,
    /// `pattern`/`colours` doesn't correspond to any segment classes the
    /// base SVG actually defines (e.g. asking for a 3-way split on an
    /// icon that only has a 2-way `horizontal` split).
    UnknownVariant {
        pattern: Option<String>,
        sections: usize,
    },
    Xml(String),
    Svg(String),
}

impl fmt::Display for RecolorError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            RecolorError::NotParametric => write!(f, "base icon has no COLORING{{}} placeholder"),
            RecolorError::UnknownVariant { pattern, sections } => write!(
                f,
                "no {sections}-section {} variant in this base icon",
                pattern.as_deref().unwrap_or("uniform")
            ),
            RecolorError::Xml(m) => write!(f, "SVG XML parse error: {m}"),
            RecolorError::Svg(m) => write!(f, "usvg parse error: {m}"),
        }
    }
}

impl std::error::Error for RecolorError {}

/// Every `{pattern}{segment}{total}` class token (e.g. `horizontal02`) in
/// the document's `class` attributes for the given `pattern` — mirrors
/// genicons.py's `findall(rf" {p}\d(\d)", svg)` via structured parsing
/// instead of a raw-text regex.
fn pattern_sections(doc: &roxmltree::Document, pattern: &str) -> BTreeSet<usize> {
    let mut sections = BTreeSet::new();
    for node in doc.descendants() {
        let Some(class) = node.attribute("class") else {
            continue;
        };
        for tok in class.split_whitespace() {
            let Some(rest) = tok.strip_prefix(pattern) else {
                continue;
            };
            let bytes = rest.as_bytes();
            if bytes.len() == 2 && bytes.iter().all(u8::is_ascii_digit) {
                sections.insert((bytes[1] - b'0') as usize);
            }
        }
    }
    sections
}

/// Whether any element carries the literal `uniform` class. genicons.py
/// assumes this unconditionally; we assert it so a base icon missing the
/// class fails loudly instead of silently rendering blank.
fn has_uniform_class(doc: &roxmltree::Document) -> bool {
    doc.descendants().any(|n| {
        n.attribute("class")
            .is_some_and(|c| c.split_whitespace().any(|t| t == "uniform"))
    })
}

/// All `(pattern, sections)` this base icon structurally supports —
/// `uniform` always included, plus whichever of [`palette::PATTERNS`] have
/// matching class tokens in the document.
fn available_patterns(doc: &roxmltree::Document) -> Vec<(Option<&'static str>, BTreeSet<usize>)> {
    let mut out = vec![(None, BTreeSet::from([1]))];
    for p in palette::PATTERNS.iter().flatten() {
        let sections = pattern_sections(doc, p);
        if !sections.is_empty() {
            out.push((Some(*p), sections));
        }
    }
    out
}

/// A `(pattern, per-segment colours)` combination, as generated by
/// [`legal_combinations`].
pub type Combination = (Option<&'static str>, Vec<Option<&'static str>>);

/// The `(pattern, segment-counts)` this base SVG structurally supports,
/// exposed for [`super::pack`] without [`legal_combinations`]'s colour-choice
/// filtering — a real chart can encode combinations that filter would never
/// generate. See docs/architecture/s52-icon-recolor.md.
pub fn structural_patterns(
    base_svg: &str,
) -> Result<Vec<(Option<&'static str>, BTreeSet<usize>)>, RecolorError> {
    let doc = roxmltree::Document::parse(base_svg).map_err(|e| RecolorError::Xml(e.to_string()))?;
    Ok(available_patterns(&doc))
}

/// Every legal `(pattern, colours)` combination genicons.py would have
/// pre-baked for `icon`'s base SVG — its own `colors_for`/`patterns_for`/
/// `product`+filter pipeline, ported. Used by tests to spot-check parity
/// against the upstream reference output; `resolve` (in
/// `chartcore::icons`) generates on demand and does not enumerate.
pub fn legal_combinations(icon: &str, base_svg: &str) -> Result<Vec<Combination>, RecolorError> {
    let doc = roxmltree::Document::parse(base_svg).map_err(|e| RecolorError::Xml(e.to_string()))?;
    let pool = palette::colours_for(icon);
    let mut out = Vec::new();
    for (pattern, sections) in available_patterns(&doc) {
        for s in sections {
            for combo in palette::colour_combinations(&pool, s) {
                out.push((pattern, combo));
            }
        }
    }
    Ok(out)
}

/// Recolor `base_svg` (one of `chartcore/assets/s52-icons/*.svg`'s raw
/// text) for `pattern` (`None` = uniform/no-pattern) with `colours` — one
/// entry per segment (`colours.len()` is the section count; `None` means
/// "leave this segment at the invisible/base default", matching
/// genicons.py's `filter(bool, cs)` skipping blank colours when building
/// per-segment overrides). Returns the fully resolved, self-contained SVG
/// (`usvg`-normalized: no `<style>`/`class` left, every shape's paint
/// baked in).
pub fn recolor_variant(
    base_svg: &str,
    pattern: Option<&str>,
    colours: &[Option<&str>],
) -> Result<String, RecolorError> {
    recolor_variant_with(base_svg, pattern, colours, ColourMode::Day)
}

/// [`recolor_variant`], on a chosen colour surface.
///
/// In [`ColourMode::Roles`] every hex this function would write is replaced
/// by its [`roles`] sentinel — the generator is the one place that knows
/// each colour's ROLE (which table a colour word came from, and that the
/// four hardcoded base-role hexes below are `ink`/`paper`), so the sentinel
/// is emitted here rather than reverse-engineered from the rendered output.
/// Nothing else changes: the same stylesheet, the same `usvg` pass, the same
/// bytes everywhere a colour is not involved.
pub fn recolor_variant_with(
    base_svg: &str,
    pattern: Option<&str>,
    colours: &[Option<&str>],
    mode: ColourMode,
) -> Result<String, RecolorError> {
    if !base_svg.contains("COLORING{}") {
        return Err(RecolorError::NotParametric);
    }
    let doc = roxmltree::Document::parse(base_svg).map_err(|e| RecolorError::Xml(e.to_string()))?;
    if !has_uniform_class(&doc) {
        return Err(RecolorError::UnknownVariant {
            pattern: None,
            sections: 1,
        });
    }

    let n = colours.len().max(1);
    let target_classes: Vec<String> = match pattern {
        None => vec!["uniform".to_string()],
        Some(p) => (0..n).map(|i| format!("{p}{i}{n}")).collect(),
    };

    // Structural check: does the base icon define an n-section split of
    // `pattern`? Not "does every per-segment class individually exist" —
    // some base icons report a section count without every index tagged;
    // this reproduces genicons.py's leniency there for parity, on purpose.
    if let Some(p) = pattern {
        if !pattern_sections(&doc, p).contains(&n) {
            return Err(RecolorError::UnknownVariant {
                pattern: Some(p.to_string()),
                sections: n,
            });
        }
    }

    let mut sheet = String::new();
    // Base role defaults (genicons.py's second, overriding pass). `ink`/
    // `paper` are the ONLY colours in the pipeline that live in Rust rather
    // than a table/asset — see docs/architecture/s52-icon-recolor.md.
    let (ink, paper) = match mode {
        ColourMode::Day => ("#000000", "#ffffff"),
        ColourMode::Roles => (roles::INK, roles::PAPER),
    };
    sheet.push_str(".fill{fill:none;stroke:none;}");
    sheet.push_str(&format!(
        ".outline{{fill:none;stroke:{ink};stroke-width:0.3;}}"
    ));
    sheet.push_str(".inline{fill:none;stroke:none;stroke-width:0.8;}");
    sheet.push_str(&format!(
        ".baseline{{fill:none;stroke:{ink};stroke-width:0.5;}}"
    ));
    sheet.push_str(&format!(
        ".basepoint{{fill:{paper};stroke:{ink};stroke-width:0.5;}}"
    ));

    // Per-segment overrides. Emitting all three role variants (fill/outline/
    // inline) as compound selectors avoids detecting which role applies —
    // it's a no-op for roles the target class doesn't co-occur with.
    //
    // Lookup order (OBJECT_COLOURS before LIGHT_COLOURS) is deliberate day-
    // byte parity with genicons.py, not the "correct" order — see
    // docs/architecture/s52-icon-recolor.md and `roles::light_colour`.
    for (i, colour) in colours.iter().enumerate().take(target_classes.len()) {
        let Some(name) = colour else { continue };
        let hex = match mode {
            ColourMode::Day => {
                palette::colour_hex(name).or_else(|| palette::light_colour_hex(name))
            }
            ColourMode::Roles => palette::colour_hex(name)
                .and_then(|_| roles::object_colour(name))
                .or_else(|| {
                    palette::light_colour_hex(name).and_then(|_| roles::light_colour(name))
                }),
        };
        let Some(hex) = hex else { continue };
        let class = &target_classes[i];
        sheet.push_str(&format!(".fill.{class}{{fill:{hex};stroke:none;}}"));
        sheet.push_str(&format!(
            ".outline.{class}{{fill:none;stroke:{hex};stroke-width:0.8;}}"
        ));
        sheet.push_str(&format!(
            ".inline.{class}{{fill:none;stroke:{hex};stroke-width:0.8;}}"
        ));
    }

    let substituted = base_svg.replacen("COLORING{}", &sheet, 1);
    normalize(&substituted)
}

/// Parse + re-serialize via `usvg`, with no recoloring — for the base
/// icons that have no `COLORING{}` placeholder at all (fixed single-colour
/// artwork like `withy-starboard.svg`/`pilpnt.svg`) and for any already-
/// generated variant a caller wants re-normalized. Doubles as the
/// well-formedness check the task's verify criteria ask for: a malformed
/// result fails here with `RecolorError::Svg`, not silently.
pub fn normalize(svg: &str) -> Result<String, RecolorError> {
    let opt = usvg::Options::default();
    let tree = usvg::Tree::from_str(svg, &opt).map_err(|e| RecolorError::Svg(e.to_string()))?;
    Ok(tree.to_string(&usvg::WriteOptions::default()))
}

