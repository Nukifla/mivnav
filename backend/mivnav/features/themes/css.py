"""Rendering the chrome half of a theme back into real CSS.

Day is deliberately absent: it stays in index.css's `@theme static` block
(Tailwind's declaration site) and is the unattributed default. See
docs/architecture/palette-runtime.md for the full rationale.
"""

from __future__ import annotations

# Contract with gen/dump_themes.mjs, which extracts this list. Listed
# explicitly (not derived from the JSON) so a stray key can't inject an
# arbitrary CSS property and a missing token shows up as a missing line.
CHROME_TOKENS: tuple[str, ...] = (
    "chrome",
    "chrome-2",
    "fg",
    "fg-2",
    "fg-3",
    "line",
    "line-2",
    "accent",
    "accent-fg",
    "ok",
    "notice",
    "alarm",
    "alarm-fg",
    "on-scrim",
    "route",
    "ap",
    "poi",
    "shadow",
)

# One entry per MapLibre-furniture rule group in index.css, same order.
# `filter` targets only `.maplibregl-ctrl-icon`, not the whole group, so
# inversion hits just the unstyleable icon, not token-aware siblings.
_FURNITURE: tuple[tuple[str, tuple[str, ...]], ...] = (
    (".maplibregl-ctrl-group", ("background: var(--color-chrome);",)),
    (".maplibregl-ctrl-group button + button", ("border-top-color: var(--color-line);",)),
    (".maplibregl-ctrl-group button:not(:disabled):hover", ("background-color: var(--color-chrome-2);",)),
    (".maplibregl-ctrl-icon", ("filter: invert(1) opacity(0.7);",)),
    (
        ".maplibregl-ctrl-scale",
        ("background-color: var(--color-chrome);", "border-color: var(--color-line);", "color: var(--color-fg-2);"),
    ),
    (".maplibregl-ctrl-attrib", ("background-color: var(--color-chrome);", "color: var(--color-fg-2);")),
    (".maplibregl-ctrl-attrib a", ("color: var(--color-fg-2);",)),
)

_HEADER = """/* GENERATED by GET /themes.css (mivnav.features.themes.css) — do not edit.
   The chrome half of every non-day palette, from the theme JSON the backend
   serves. Day is the unattributed default and is declared in index.css's
   `@theme static` block instead; see that file and this module's docstring. */
"""


def _selector(theme_id: str, suffix: str = "") -> str:
    tail = f" {suffix}" if suffix else ""
    return ':root[data-palette="' + theme_id + '"]' + tail


def _palette_block(theme: dict) -> str:
    lines = [_selector(theme["id"]) + " {"]
    if theme.get("dark"):
        # Without this the UA paints scrollbars/focus rings/form controls
        # from the light scheme even on a dark palette.
        lines.append("  color-scheme: dark;")
    chrome = theme.get("chrome") or {}
    for token in CHROME_TOKENS:
        value = chrome.get(token)
        if value is not None:
            lines.append(f"  --color-{token}: {value};")
    lines.append("}")
    return "\n".join(lines)


def _furniture_block(dark_ids: list[str]) -> str:
    out = []
    for suffix, decls in _FURNITURE:
        selector = ",\n".join(_selector(i, suffix) for i in dark_ids)
        body = "\n".join(f"  {d}" for d in decls)
        out.append(f"{selector} {{\n{body}\n}}")
    return "\n".join(out)


def render_css(themes: tuple[dict, ...]) -> str:
    """The whole stylesheet: one block per non-day palette, then the
    dark-palette MapLibre overrides. Deterministic in theme order, so an
    unchanged theme set always hashes to the same ETag."""
    blocks = [_palette_block(t) for t in themes if t["id"] != "day"]
    dark_ids = [t["id"] for t in themes if t.get("dark") and t["id"] != "day"]
    if dark_ids:
        blocks.append(_furniture_block(dark_ids))
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"
